import {test, expect} from './fixtures.ts';
import {holdWorkerRequest} from './worker-control.ts';

test('diagnostics are opt-in while loading and errors remain visible', async ({page}) => {
  await page.goto('/');
  const toggle = page.locator('#diagnosis-mode');
  const metrics = ['timeline-availability', 'render-lead', 'audio-diagnostics', 'timeline-view-note'];
  await expect(toggle).toHaveText('Diagnosis mode');
  await expect(toggle).toBeVisible();
  expect(await toggle.evaluate(element => getComputedStyle(element).color)).toBe(await page.locator('#timeline-help > summary').evaluate(element => getComputedStyle(element).color));
  for (const id of metrics) await expect(page.locator(`#${id}`)).toBeHidden();
  await page.locator('#load-button').click();
  await expect(page.locator('#play-button')).toBeEnabled();
  await page.locator('#play-button').click();
  await expect.poll(() => page.locator('#seek-slider').inputValue().then(Number)).toBeGreaterThan(.1);
  await page.locator('#play-button').click();
  await expect(page.locator('#play-status')).toHaveText('Paused');
  await expect(page.locator('#timeline-direction')).toHaveCount(0);
  await page.locator('#return-button').click();
  await expect(page.locator('#timeline-scale')).toBeVisible();
  const heard = await page.locator('#seek-slider').inputValue();
  const laneTop = await page.locator('#voice-lane-0').evaluate(element => element.getBoundingClientRect().top);
  await toggle.focus();
  await toggle.press('Enter');
  await expect(toggle).toHaveAttribute('aria-checked', 'true');
  for (const id of metrics) await expect(page.locator(`#${id}`)).toBeVisible();
  await expect(page.locator('#timeline-availability')).toContainText('Upcoming prepared to');
  await expect(page.locator('#render-lead')).toContainText('audio queue');
  await expect(page.locator('#audio-diagnostics')).toContainText('buffer underruns');
  expect(await page.locator('#voice-lane-0').evaluate(element => element.getBoundingClientRect().top)).toBe(laneTop);
  await expect(page.locator('#seek-slider')).toHaveValue(heard);
  await toggle.press('Enter');
  for (const id of metrics) await expect(page.locator(`#${id}`)).toBeHidden();
  await page.locator('#playback-setup > summary').click();
  const release = await holdWorkerRequest(page, 'load');
  await page.locator('#load-button').click();
  await expect(page.locator('#play-status')).toHaveText('Loading…');
  await expect(page.locator('#status-message')).toBeVisible();
  await release('Diagnostic check failure');
  await expect(page.locator('#status-message')).toBeVisible();
  await expect(page.locator('#status-message')).toContainText('Diagnostic check failure');
  for (const id of metrics) await expect(page.locator(`#${id}`)).toBeHidden();
  await page.setViewportSize({width:390, height:844});
  await expect(toggle).toBeVisible();
  await toggle.click();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
