import {test, expect} from './fixtures.ts';
import {holdWorkerRequest} from './worker-control.ts';

test('inspector owns voice controls and chip switches preserve mute preferences', async ({page}) => {
  await page.goto('/');
  await page.locator('#sample-select').selectOption('bach-toccata-stereo');
  await page.locator('#load-button').click();
  await expect(page.locator('#play-button')).toBeEnabled();
  await page.locator('#play-button').click();
  await expect.poll(() => page.locator('#seek-slider').inputValue().then(Number)).toBeGreaterThan(.1);
  await page.locator('#play-button').click();
  await expect(page.locator('#play-status')).toHaveText('Paused');
  await expect(page.locator('#timeline-panel #mute-0, #timeline-panel #restore-button')).toHaveCount(0);
  await expect(page.locator('.inspector #mute-0, .inspector #restore-button')).toHaveCount(2);
  await page.locator('#mute-0').click();
  await expect(page.locator('#mute-0')).toHaveAttribute('aria-pressed', 'true');
  const release = await holdWorkerRequest(page, 'mute');
  await page.locator('#chip-enabled-0').click();
  await expect(page.locator('#mix-controls')).toHaveAttribute('aria-busy', 'true');
  await expect(page.locator('#chip-enabled-1')).toBeDisabled();
  await release();
  await expect(page.locator('#chip-enabled-0')).toHaveAttribute('aria-checked', 'false');
  await expect(page.locator('#chip-enabled-1')).toHaveAttribute('aria-checked', 'true');
  await page.locator('#chip-enabled-0').click();
  await expect(page.locator('#chip-enabled-0')).toHaveAttribute('aria-checked', 'true');
  await expect(page.locator('#mute-0')).toHaveAttribute('aria-pressed', 'true');
  await expect(page.locator('#mute-1')).toHaveAttribute('aria-pressed', 'false');
  await page.locator('#chip-enabled-1').click();
  await expect(page.locator('#chip-enabled-1')).toHaveAttribute('aria-checked', 'false');
  await page.locator('#solo-3').click();
  await expect(page.locator('#chip-enabled-1')).toHaveAttribute('aria-checked', 'true');
  await expect(page.locator('#solo-3')).toHaveAttribute('aria-pressed', 'true');
  await page.locator('#chip-enabled-0').click();
  await expect(page.locator('#chip-enabled-0')).toHaveAttribute('aria-checked', 'false');
  await page.locator('#restore-button').click();
  for (const chip of [0, 1]) await expect(page.locator(`#chip-enabled-${chip}`)).toHaveAttribute('aria-checked', 'true');
  for (let voice = 0; voice < 6; voice++) await expect(page.locator(`#mute-${voice}`)).toHaveAttribute('aria-pressed', 'false');
  await page.locator('.inspector').screenshot({path: `build/ui-controls/${test.info().project.name}-inspector.png`});
  await page.setViewportSize({width: 390, height: 844});
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.locator('.inspector').screenshot({path: `build/ui-controls/${test.info().project.name}-inspector-narrow.png`});
  await page.locator('#sample-select').selectOption('rambo-loader-main');
  await page.locator('#load-button').click();
  await expect(page.locator('#play-button')).toBeEnabled();
  await expect(page.locator('#mixer-chip-1')).toBeHidden();
  await expect(page.locator('#chip-enabled-0')).toHaveAttribute('aria-checked', 'true');
});
