import {test, expect} from './fixtures.ts';
import {holdWorkerRequest} from './worker-control.ts';
import {installLibraryProvider, chooseFixtureWithPointer, libraryTitle, fixtureSidBytes} from './library-picker-fixture.ts';
import {monoSid} from '../fixtures/dual-sid.ts';

test('recent library songs persist deduplicate reload on selection and clear without recording local files', async ({page}) => {
  await installLibraryProvider(page);
  let downloads = 0;
  let fail = false;
  await page.route('https://www.hvsc.c64.org/download/C64Music/MUSICIANS/**', route => {
    downloads++;
    return route.fulfill({status: fail ? 503 : 200, body: fail ? 'Unavailable' : Buffer.from(monoSid('MOS6581', 0))});
  });
  await page.goto('/');
  const recent = page.getByLabel('Recently played', {exact: true});
  await expect(recent).toBeHidden();
  await page.locator('#local-file').setInputFiles({name: 'private.sid', mimeType: 'application/octet-stream', buffer: fixtureSidBytes()});
  await expect(page.locator('#play-button')).toBeEnabled();
  await page.locator('#play-button').click();
  await expect.poll(() => page.locator('#seek-slider').inputValue().then(Number)).toBeGreaterThan(.1);
  await page.locator('#play-button').click();
  await expect(recent).toBeHidden();
  await page.locator('#browse-library').click();
  await chooseFixtureWithPointer(page, 'valid');
  await expect(page.locator('#play-status')).toHaveText('Ready');
  await expect(recent).toBeVisible();
  await expect(recent.locator('option')).toHaveCount(2);
  await expect(recent.locator('option').nth(1)).toContainText(libraryTitle);
  await page.locator('#sid-highlights').selectOption('QfM49EtP');
  await expect(page.locator('#track-title')).toHaveText('Cybernoid II');
  await expect(recent.locator('option')).toHaveCount(3);
  await expect(recent.locator('option').nth(1)).toContainText('Cybernoid II');
  await recent.selectOption('MUSICIANS/F/Fixture/Rambo.sid');
  await expect(page.locator('#track-title')).toHaveText(libraryTitle);
  await expect(recent.locator('option').nth(1)).toContainText(libraryTitle);
  await expect(recent.locator('option')).toHaveCount(3);
  fail = true;
  await recent.selectOption('MUSICIANS/T/Tel_Jeroen/Cybernoid_II.sid');
  await expect(page.locator('#status-message')).toContainText('503');
  await expect(recent.locator('option').nth(1)).toContainText(libraryTitle);
  fail = false;
  const release = await holdWorkerRequest(page, 'load');
  await recent.selectOption('MUSICIANS/T/Tel_Jeroen/Cybernoid_II.sid');
  await expect(recent).toBeDisabled();
  await expect(page.getByRole('button', {name: 'Clear history', exact: true})).toBeDisabled();
  await release('Recent song load failed');
  await expect(page.locator('#status-message')).toContainText('Recent song load failed');
  await expect(recent.locator('option').nth(1)).toContainText(libraryTitle);
  const beforeReload = downloads;
  await page.reload();
  await expect(recent.locator('option')).toHaveCount(3);
  expect(downloads).toBe(beforeReload);
  await page.setViewportSize({width: 390, height: 844});
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.locator('.sidebar').screenshot({path: `build/recent-songs/${test.info().project.name}-recent-narrow.png`});
  await recent.selectOption('MUSICIANS/T/Tel_Jeroen/Cybernoid_II.sid');
  await expect(page.locator('#track-title')).toHaveText('Cybernoid II');
  await page.locator('#play-button').click();
  await expect.poll(() => page.locator('#seek-slider').inputValue().then(Number)).toBeGreaterThan(.1);
  await page.getByRole('button', {name: 'Clear history', exact: true}).click();
  await expect(recent).toBeHidden();
  await page.reload();
  await expect(recent).toBeHidden();
  await page.locator('#load-button').click();
  await expect(page.locator('#play-button')).toBeEnabled();
  await page.locator('#play-button').click();
  await expect.poll(() => page.locator('#seek-slider').inputValue().then(Number)).toBeGreaterThan(.1);
  await expect(recent).toBeHidden();
});
